<template>
	<div class="flex-1 flex min-h-0 h-[calc(100vh-56px)]">
		<aside class="hidden md:flex w-80 shrink-0 flex-col gap-6 border-r border-slate-200 dark:border-slate-800 bg-white/60 dark:bg-slate-900/40 p-4 min-h-0">
			<DocumentsPanel class="max-h-[55%]" />
			<ChatConversations class="flex-1" />
		</aside>

		<main class="flex-1 flex flex-col min-w-0">
			<div ref="scroller" class="flex-1 overflow-y-auto scroll-thin">
				<div class="max-w-3xl mx-auto px-4 py-6 space-y-6">
					<div v-if="!chat.current?.messages.length" class="flex flex-col items-center text-center pt-16">
						<div class="w-14 h-14 rounded-2xl bg-primary-50 dark:bg-primary-600/15 text-primary-600 flex-center mb-4">
							<Icon name="lucide:file-search" size="28" />
						</div>
						<h1 class="text-xl font-semibold">Ask your documents</h1>
						<p class="text-sm text-slate-500 mt-1 max-w-md">
							{{ documents.ready.length ? 'Answers come only from your files, with links to the exact page.' : 'Upload a PDF, Word or text file to start.' }}
						</p>
						<div v-if="documents.ready.length" class="flex flex-wrap justify-center gap-2 mt-6">
							<button
								v-for="example in examples"
								:key="example"
								class="rounded-full border border-slate-200 dark:border-slate-700 px-3.5 py-1.5 text-sm hover:border-primary-500 hover:text-primary-600 transition-300 cursor-pointer"
								@click="ask(example)"
							>
								{{ example }}
							</button>
						</div>
						<DocumentsPanel class="md:hidden w-full mt-8 text-left" />
					</div>

					<ChatMessage v-for="message in chat.current?.messages" :key="message.id" :message="message" />
					<UIAlert :text="chat.error" />
				</div>
			</div>

			<div class="max-w-3xl w-full mx-auto px-4 pb-4 pt-2">
				<ChatComposer :disabled="chat.answering || !documents.ready.length" @send="ask" />
				<p class="text-[11px] text-center text-slate-400 mt-2">Answers are generated by Claude from your documents and can still be wrong.</p>
			</div>
		</main>
	</div>
</template>

<script lang="ts" setup>
useHead({ title: 'Ask your documents' })

const documents = useDocumentsStore()
const chat = useChatStore()

await Promise.all([documents.load(), chat.loadConversations()])

const examples = ['What is this document about?', 'Summarize the main points', 'What are the key dates?']

const scroller = ref<HTMLElement>()
// Keep the newest text in view while the answer streams in
watch(
	() => chat.current?.messages.at(-1)?.content,
	() => nextTick(() => scroller.value?.scrollTo({ top: scroller.value.scrollHeight })),
	{ flush: 'post' }
)

function ask(question: string) {
	chat.ask(question)
}
</script>
